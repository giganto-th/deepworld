// Site root, also on pages served with <base href="../">.
export const siteRoot = new URL('./', document.baseURI);
const relPath = () => decodeURIComponent(location.pathname).slice(decodeURIComponent(siteRoot.pathname).length);

function detect() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q === 'th' || q === 'en') return q;
  return relPath().startsWith('en/') ? 'en' : 'th';
}

export let lang = detect();

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.th[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export const locale = () => (lang === 'th' ? 'th-TH' : 'en-US');

// Fills elements marked data-i18n="key" (text), data-i18n-html="key" (markup from the
// dictionary only) and data-i18n-attr="attr:key;attr:key".
export function applyDom(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  }
}

// URL of a page ('world' | 'thai') in a language.
export function pageUrl(mode, language = lang) {
  return new URL(`${language === 'en' ? 'en/' : ''}${mode === 'thai' ? 'thai/' : ''}`, siteRoot).toString();
}

// Switching language goes to the same page under the other language's URL.
export function switchLanguage() {
  const thai = /(^|\/)thai\/?$/.test(relPath());
  location.href = pageUrl(thai ? 'thai' : 'world', lang === 'th' ? 'en' : 'th');
}
